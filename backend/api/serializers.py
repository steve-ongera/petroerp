"""
Serializers. Most are generated by make_serializer() so every model exposes the same behaviour:
  * system-managed fields (created_by, status, reference, totals, journals) are READ-ONLY
  * foreign keys also return a human label  (supplier -> supplier_label)
  * sensitive fields (password, mfa_secret) never leave the server
Nested documents (PO, invoices, orders, shipments) are written atomically with their lines.
"""
from django.db import transaction
from rest_framework import serializers

from . import models as m
from . import services as svc

SYSTEM_RO = {'created_at', 'updated_at', 'created_by'}
DOC_RO = {'subtotal', 'tax_total', 'total', 'amount_paid', 'amount_credited', 'match_status', 'match_notes',
          'received_quantity', 'delivered_quantity', 'invoiced_quantity', 'margin_pct'}


class BaseSerializer(serializers.ModelSerializer):
    """Adds <fk>_label next to every foreign key so tables never show raw ids."""

    def to_representation(self, instance):
        data = super().to_representation(instance)
        for name, field in self.fields.items():
            if isinstance(field, serializers.PrimaryKeyRelatedField) and data.get(name) is not None:
                obj = getattr(instance, name, None)
                data[f'{name}_label'] = str(obj) if obj is not None else None
        return data


def make_serializer(model, read_only=(), computed=(), exclude=(), extra=None):
    names = {f.name for f in model._meta.get_fields()}
    ro = set(read_only) | SYSTEM_RO
    if getattr(model, 'STATUS_MANAGED', False):
        ro |= {'status', 'reference'}
    attrs = {c: serializers.ReadOnlyField() for c in computed}
    attrs.update(extra or {})
    meta = {'model': model, 'read_only_fields': [f for f in ro if f in names]}
    if exclude:
        meta['exclude'] = list(exclude)
    else:
        meta['fields'] = '__all__'
    attrs['Meta'] = type('Meta', (), meta)
    return type(f'{model.__name__}Serializer', (BaseSerializer,), attrs)


def make_nested(model, line_model, parent_field, read_only=(), computed=()):
    """Header + lines written in one transaction. Lines recompute tax/totals and (sales) pricing."""
    Line = make_serializer(line_model, read_only=DOC_RO, exclude=(parent_field,))

    class Nested(make_serializer(model, read_only=DOC_RO | set(read_only), computed=computed, extra={'lines': Line(many=True)})):
        def _save_lines(self, obj, lines):
            user = self.context['request'].user
            on = getattr(obj, getattr(obj, 'FX_DATE', 'created_at'), None) or svc.today()
            for ln in lines:
                ln = dict(ln)
                if ln.get('tax_code') and not ln.get('tax_rate'):
                    ln['tax_rate'] = svc.get_tax_rate(obj.company, ln['tax_code'], on)
                if line_model is m.SalesOrderLine:
                    svc.apply_line_pricing(obj.company, ln, obj.contract, obj.order_date, user)
                line_model.objects.create(**{parent_field: obj}, **ln)
            if hasattr(obj, 'recalc'):
                obj.recalc()

        @transaction.atomic
        def create(self, vd):
            lines = vd.pop('lines', [])
            vd.setdefault('created_by', self.context['request'].user)
            obj = model.objects.create(**vd)
            self._save_lines(obj, lines)
            return obj

        @transaction.atomic
        def update(self, instance, vd):
            lines = vd.pop('lines', None)
            for k, v in vd.items():
                setattr(instance, k, v)
            instance.save()
            if lines is not None:
                instance.lines.all().delete()
                self._save_lines(instance, lines)
            return instance

    Nested.__name__ = f'{model.__name__}Serializer'
    return Nested


