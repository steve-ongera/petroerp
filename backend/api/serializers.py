class UserSerializer(serializers.ModelSerializer):
    password = serializers.CharField(write_only=True, required=False, min_length=10)
    role_name = serializers.CharField(source='role.name', read_only=True, default=None)

    class Meta:
        model = m.User
        fields = ['id', 'username', 'email', 'first_name', 'last_name', 'phone', 'role', 'role_name', 'companies',
                  'is_active', 'password']

    def create(self, vd):
        pw, comps = vd.pop('password', None), vd.pop('companies', [])
        u = m.User(**vd)
        u.set_password(pw) if pw else u.set_unusable_password()
        u.save()
        u.companies.set(comps)
        return u

    def update(self, inst, vd):
        pw = vd.pop('password', None)
        comps = vd.pop('companies', None)
        for k, v in vd.items():
            setattr(inst, k, v)
        if pw:
            inst.set_password(pw)
        inst.save()
        if comps is not None:
            inst.companies.set(comps)
        return inst


